CREATE TABLE IF NOT EXISTS visit_days (day TEXT NOT NULL, token TEXT NOT NULL, PRIMARY KEY(day, token));
CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK(id=1), visits INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO totals(id, visits) VALUES(1, 0);
CREATE TRIGGER IF NOT EXISTS count_new_visit AFTER INSERT ON visit_days BEGIN
  UPDATE totals SET visits=visits+1 WHERE id=1;
END;
